#!/usr/bin/env python3
"""Generate ../../../src/core/vanilla_records.h from the extracted shipping
weapon records (data/mis/mpl/*.wpb, 96 bytes each).

Usage:
    python tools/gen_vanilla_header.py [--wpb-dir work/a/data/data/mis/mpl]

The header embeds the exact bytes of the three missile records we can label
(msl / misf / misf2) so the mod can locate them in memory with a byte-pattern
scan, plus the field offsets decoded from the shipping data (docs/VANILLA.md).
Regenerate after a game update: extract a.arc with tools/arc/arc_tool.py, then
run this script again.
"""
import argparse
import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_DIR = os.path.join(ROOT, "work", "a", "data", "data", "mis", "mpl")
OUT = os.path.join(ROOT, "src", "core", "vanilla_records.h")

# record keys we embed; (file, model key)
RECORDS = [
    ("mis.wpb", "msl"),     # player standard missile
    ("misf.wpb", "misf"),   # wingman standard missile
    ("misf2.wpb", "misf2"), # second wingman variant
]

# Field offsets in the 96-byte record (docs/VANILLA.md §2, verified on 10 files)
OFFSETS = [
    ("kDataOff", 0x00, "u32 data_off, always 0x10"),
    ("kAltMin", 0x10, "f32"),
    ("kAltMax", 0x14, "f32"),
    ("kRadius", 0x18, "f32"),
    ("kExplPers", 0x1C, "f32"),
    ("kScope", 0x20, "f32 lock-on / seeker acquisition range (m)"),
    ("kRange", 0x24, "f32 max flight distance (m)"),
    ("kHitRadius", 0x28, "f32"),
    ("kTimeStart", 0x2C, "f32"),
    ("kTimeWait", 0x30, "f32 guidance phase duration (s)"),
    ("kTimeStep", 0x34, "f32"),
    ("kTimeContinue", 0x38, "f32"),
    ("kLead", 0x3C, "f32 lead / pursuit gain - the PN source field"),
    ("kDispersionAng", 0x40, "f32"),
    ("kAccFall", 0x44, "f32"),
    ("kSpeed", 0x54, "u16"),
    ("kType", 0x58, "u8 1 = gun, 2 = missile"),
    ("kAttack", 0x59, "u8"),
    ("kStartAng", 0x5A, "u8 seeker cone / start angle (deg)"),
]

RECORD_SIZE = 96


def load(path):
    with open(path, "rb") as f:
        data = f.read()
    if len(data) != RECORD_SIZE:
        raise SystemExit(f"{path}: expected {RECORD_SIZE} bytes, got {len(data)}")
    return data


def fmt_bytes(b):
    return ", ".join(f"0x{x:02X}" for x in b)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wpb-dir", default=DEFAULT_DIR)
    ap.add_argument("--out", default=OUT)
    args = ap.parse_args()

    records = []
    for filename, key in RECORDS:
        path = os.path.join(args.wpb_dir, filename)
        if not os.path.exists(path):
            print(f"warning: {path} missing, skipping", file=sys.stderr)
            continue
        data = load(path)
        # sanity: data_off == 0x10, type == 2 for missiles
        data_off = struct.unpack_from("<I", data, 0)[0]
        typ = data[0x58]
        lead = struct.unpack_from("<f", data, 0x3C)[0]
        sc = struct.unpack_from("<f", data, 0x20)[0]
        rg = struct.unpack_from("<f", data, 0x24)[0]
        sa = data[0x5A]
        records.append((key, filename, data))
        print(f"{key:6s} {filename:12s} data_off=0x{data_off:X} type={typ} "
              f"lead={lead:.1f} scope={sc:.0f} range={rg:.0f} startAng={sa}")

    if not records:
        raise SystemExit("no records found - extract a.arc first")

    lines = []
    A = lines.append
    A("// ACZPropNav - shipping weapon record bytes and field offsets.")
    A("//")
    A("// GENERATED by tools/gen_vanilla_header.py from the extracted shipping")
    A("// archives (a.arc -> data/mis/mpl/*.wpb). Do not edit by hand.")
    A("//")
    A("// The mod scans writable memory for the exact 96-byte record pattern of")
    A("// these missiles (the game loads them verbatim from data/mis/mpl), and")
    A("// then writes the guidance fields at the offsets below. docs/VANILLA.md")
    A("// documents how every offset was proven.")
    A("#pragma once")
    A("")
    A("#include <cstdint>")
    A("")
    A("namespace acz::vanilla {")
    A("")
    A(f"constexpr uint32_t kRecordSize = {RECORD_SIZE};")
    A("")
    for name, off, comment in OFFSETS:
        A(f"constexpr uint32_t {name} = 0x{off:02X}; // {comment}")
    A("")
    A("struct Record {")
    A("    const char* key;      // model key, e.g. \"msl\"")
    A("    const char* source;   // original file name in data/mis/mpl")
    A("    uint8_t bytes[kRecordSize];")
    A("};")
    A("")
    A(f"inline constexpr Record kRecords[{len(records)}] = {{")
    for key, filename, data in records:
        A("    {")
        A(f"        \"{key}\", \"{filename}\",")
        A(f"        {{{fmt_bytes(data[:48])},")
        A(f"         {fmt_bytes(data[48:])}}},")
        A("    },")
    A("};")
    A("")
    A(f"inline constexpr int kRecordCount = {len(records)};")
    A("")
    A("// Byte window used as the scan needle: scope, range and hitRadius are the")
    A("// most distinctive stable fields (they differ between the three records and")
    A("// a hand-edited mod changes them deliberately, but they never collide by")
    A("// accident). Everything else is validated after the hit.")
    A("constexpr uint32_t kNeedleOffset = kScope;")
    A("constexpr uint32_t kNeedleSize = 12;")
    A("")
    A("} // namespace acz::vanilla")
    A("")

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
